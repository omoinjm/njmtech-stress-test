// Pure (no server imports): used by the client report page and the server-rendered admin page.
import type { LoadTestSummary, ScanKind } from "../db/schema";
import { SEVERITY_ORDER, severityRank, type Severity } from "../scanner/types";

export type MarkdownFinding = { severity: Severity; title: string; evidence: string; impact: string; fix: string };

export type MarkdownReportInput = {
  origin: string;
  kind: ScanKind;
  scannedAt: string | Date;
  score: number;
  findings: MarkdownFinding[];
  loadTest?: LoadTestSummary | null;
};

const SEV_ICON: Record<Severity, string> = { critical: "🔴", high: "🟠", medium: "🟡", low: "🔵", info: "⚪" };

/** Fence text safely even if it contains backticks. */
function fence(text: string) {
  const longest = Math.max(2, ...(text.match(/`+/g) ?? []).map((m) => m.length));
  const f = "`".repeat(longest + 1);
  return `${f}\n${text.trim()}\n${f}`;
}

/** Keep single-line fields (titles, table cells) from breaking the Markdown structure. */
const inline = (s: string) => s.replace(/\r?\n/g, " ").replace(/\|/g, "\\|").trim();

export function reportToMarkdown(r: MarkdownReportInput): string {
  const host = new URL(r.origin).host;
  const date = new Date(r.scannedAt).toISOString().slice(0, 10);
  const findings = [...r.findings].sort((a, b) => severityRank(a.severity) - severityRank(b.severity));
  const counts = SEVERITY_ORDER.map((s) => [s, findings.filter((f) => f.severity === s).length] as const).filter(([, n]) => n > 0);

  const out: string[] = [
    `# Security report: ${host}`,
    "",
    `- **Site:** ${r.origin}`,
    `- **Scan:** ${r.kind === "deep" ? "Deep scan" : "Public scan"} · ${date}`,
    `- **Score:** ${r.score}/100`,
    `- **Issues:** ${findings.length === 0 ? "none found" : counts.map(([s, n]) => `${n} ${s}`).join(", ")}`,
    "",
  ];

  if (findings.length) {
    out.push("## Summary", "", "| # | Severity | Issue |", "|---|---|---|");
    findings.forEach((f, i) => out.push(`| ${i + 1} | ${SEV_ICON[f.severity]} ${f.severity} | ${inline(f.title)} |`));
    out.push("");
  }

  const lt = r.loadTest;
  if (lt) {
    out.push(
      "## Stress test",
      "",
      `- **Peak concurrent users:** ${lt.peakConcurrency}`,
      `- **Requests:** ${lt.requests} (${lt.rps} req/s)`,
      `- **Error rate:** ${(lt.errorRate * 100).toFixed(1)}%`,
      `- **Response time:** p50 ${lt.p50Ms} ms · p95 ${lt.p95Ms} ms · max ${lt.maxMs} ms`,
      ...(lt.abortedEarly ? ["- **Note:** the test was stopped early because the site started failing."] : []),
      "",
    );
  }

  if (findings.length) {
    out.push("## Findings", "");
    findings.forEach((f, i) => {
      out.push(
        `### ${i + 1}. ${inline(f.title)}`,
        "",
        `**Severity:** ${SEV_ICON[f.severity]} ${f.severity}`,
        "",
        `**Why it matters:** ${f.impact.trim()}`,
        "",
        "**What we saw:**",
        "",
        fence(f.evidence),
        "",
        "**How to fix it:**",
        "",
        fence(f.fix),
        "",
      );
    });
  }

  out.push("---", `_Generated by NJM Tech Security · https://security.njmtech.co.za_`, "");
  return out.join("\n");
}
